#!/usr/bin/env bash
# Integration tests for the Netplane LLM documentation generator.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TEST_ROOT="$(mktemp -d)"
trap 'rm -rf "${TEST_ROOT}"' EXIT

SOURCES=(
    README.md
    AGENTS.md
    CONTRIBUTING.md
    docs/architecture.md
    docs/architecture/execution-semantics.md
    docs/http-boundaries.md
    docs/adr/0001-tower-service-model.md
    docs/adr/0002-runtime-reconfiguration.md
    docs/adr/0003-crate-boundaries.md
    docs/adr/0004-graph-composition.md
    docs/adr/0005-reconfiguration-control.md
    QUICKSTART.md
    SECURITY.md
)

mkdir -p "${TEST_ROOT}/scripts"
cp "${REPO_ROOT}/scripts/generate-llms-txt.sh" "${TEST_ROOT}/scripts/"
printf '0.0.0\n' > "${TEST_ROOT}/VERSION"
for source in "${SOURCES[@]}"; do
    mkdir -p "${TEST_ROOT}/$(dirname "${source}")"
    printf 'Content from %s\n' "${source}" > "${TEST_ROOT}/${source}"
done

bash "${TEST_ROOT}/scripts/generate-llms-txt.sh"
[[ -f "${TEST_ROOT}/llms.txt" && -f "${TEST_ROOT}/llms-full.txt" ]]
grep -q '^# Netplane$' "${TEST_ROOT}/llms.txt"
grep -q '^# Netplane - Full LLM Context$' "${TEST_ROOT}/llms-full.txt"
grep -q '^> Generated by scripts/generate-llms-txt.sh. Version: 0.0.0$' "${TEST_ROOT}/llms.txt"
grep -q '^> Generated by scripts/generate-llms-txt.sh. Version: 0.0.0$' "${TEST_ROOT}/llms-full.txt"
if grep -q 'Rust 2026 Template' "${TEST_ROOT}/llms.txt" "${TEST_ROOT}/llms-full.txt"; then
    echo 'Template identity remains in generated output' >&2
    exit 1
fi

expected_sources=(llms.txt "${SOURCES[@]}")
previous_line=0
for source in "${expected_sources[@]}"; do
    line="$(grep -nFx "## Source: ${source}" "${TEST_ROOT}/llms-full.txt" | cut -d: -f1)"
    [[ -n "${line}" && "${line}" -gt "${previous_line}" ]]
    previous_line="${line}"
    grep -qFx "> Relative links in this section resolve from $(dirname "${source}")." "${TEST_ROOT}/llms-full.txt"
done
[[ "$(grep -c '^## Source: ' "${TEST_ROOT}/llms-full.txt")" -eq "${#expected_sources[@]}" ]]

cp "${TEST_ROOT}/llms.txt" "${TEST_ROOT}/first-llms.txt"
cp "${TEST_ROOT}/llms-full.txt" "${TEST_ROOT}/first-llms-full.txt"
bash "${TEST_ROOT}/scripts/generate-llms-txt.sh"
cmp "${TEST_ROOT}/first-llms.txt" "${TEST_ROOT}/llms.txt"
cmp "${TEST_ROOT}/first-llms-full.txt" "${TEST_ROOT}/llms-full.txt"

mv "${TEST_ROOT}/AGENTS.md" "${TEST_ROOT}/missing-AGENTS.md"
if bash "${TEST_ROOT}/scripts/generate-llms-txt.sh" > "${TEST_ROOT}/error.log" 2>&1; then
    echo 'Missing required source unexpectedly succeeded' >&2
    exit 1
fi
grep -qFx 'Missing required generator input: AGENTS.md' "${TEST_ROOT}/error.log"
cmp "${TEST_ROOT}/first-llms.txt" "${TEST_ROOT}/llms.txt"
cmp "${TEST_ROOT}/first-llms-full.txt" "${TEST_ROOT}/llms-full.txt"
mv "${TEST_ROOT}/missing-AGENTS.md" "${TEST_ROOT}/AGENTS.md"

mv "${TEST_ROOT}/VERSION" "${TEST_ROOT}/missing-VERSION"
if bash "${TEST_ROOT}/scripts/generate-llms-txt.sh" > "${TEST_ROOT}/error.log" 2>&1; then
    echo 'Missing VERSION unexpectedly succeeded' >&2
    exit 1
fi
grep -qFx 'Missing required generator input: VERSION' "${TEST_ROOT}/error.log"
cmp "${TEST_ROOT}/first-llms.txt" "${TEST_ROOT}/llms.txt"
cmp "${TEST_ROOT}/first-llms-full.txt" "${TEST_ROOT}/llms-full.txt"

echo 'LLM generator tests passed'
