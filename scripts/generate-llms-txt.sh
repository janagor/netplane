#!/usr/bin/env bash
# Generate concise and full Netplane context from repository documentation.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LLMS_FILE="${REPO_ROOT}/llms.txt"
FULL_FILE="${REPO_ROOT}/llms-full.txt"

SOURCES=(
    llms.txt
    README.md
    AGENTS.md
    CONTRIBUTING.md
    docs/architecture.md
    docs/architecture/execution-semantics.md
    docs/adr/0001-tower-service-model.md
    docs/adr/0002-runtime-reconfiguration.md
    docs/adr/0003-crate-boundaries.md
    QUICKSTART.md
    SECURITY.md
)

for source in VERSION "${SOURCES[@]:1}"; do
    if [[ ! -f "${REPO_ROOT}/${source}" ]]; then
        printf 'Missing required generator input: %s\n' "${source}" >&2
        exit 1
    fi
done

cat > "${LLMS_FILE}" << OVERVIEW
# Netplane

> Transport-independent Rust library for dynamically reconfigurable Tower service compositions.
> Generated by scripts/generate-llms-txt.sh. Version: $(cat "${REPO_ROOT}/VERSION")

## Implemented

- Bounded Tower service execution with readiness and dispatch on the same service instance.
- Atomic publication of complete, immutable versions using ArcSwapOption.
- Synchronous version selection at Handle::execute() invocation; accepted requests retain that version until completion or future drop.
- Queued-request cancellation, worker cleanup, and graceful, retryable shutdown draining.

## Limits and planned work

- Concurrency and buffer bounds are per version; there is no global admission budget.
- GraphDraft validates positive capacities, not topology or application policy.
- There is no general-purpose graph construction API.
- Global admission budgeting, observability, a reconfiguration control API, HTTP integration, and general graph composition are planned.

## Workspace and authoritative documents

- [crates/netplane](crates/netplane/): Public runtime library; transport and deployment independent.
- [crates/xtask](crates/xtask/): Development tooling; never a runtime dependency.
- [README.md](README.md): Project overview and local commands.
- [AGENTS.md](AGENTS.md): Coding contract and runtime invariants.
- [docs/architecture.md](docs/architecture.md): Architecture and current limits.
- [docs/architecture/execution-semantics.md](docs/architecture/execution-semantics.md): Canonical runtime behavior contract.
- [docs/adr/](docs/adr/): Accepted architectural decisions.

## Verification

Run cargo fmt --all -- --check, cargo clippy --workspace --all-targets --all-features -- -D warnings, cargo build --workspace --all-targets, cargo test --workspace, and the live_reconfiguration example.
OVERVIEW

{
    printf '# Netplane - Full LLM Context\n\n'
    printf '> Generated by scripts/generate-llms-txt.sh. Version: %s\n\n' "$(cat "${REPO_ROOT}/VERSION")"
    first_source=true
    for source in "${SOURCES[@]}"; do
        if [[ "${first_source}" == false ]]; then
            printf '\n'
        fi
        first_source=false
        printf '## Source: %s\n\n' "${source}"
        printf '> Relative links in this section resolve from %s.\n\n' "$(dirname "${source}")"
        cat "${REPO_ROOT}/${source}"
    done
} > "${FULL_FILE}"
